// Pasteboard/PasteboardReader.swift
// Hermes
//
// Turns a drop or the clipboard into shelf entries, picking the most useful representation.

import AppKit
import UniformTypeIdentifiers

struct PasteboardReader {
    let storage: ItemStorage

    enum Preference {
        /// Drops: an image dragged from a browser should land as the image, not its address.
        case images
        /// The clipboard: copied text often carries a rendered image alongside it.
        case text
    }

    static let concealedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword")
    ]

    static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff, .init(UTType.jpeg.identifier), .init(UTType.heic.identifier), .init(UTType.gif.identifier)
    ]

    /// Marked by password managers and the like as not for keeping.
    static func isConcealed(_ pasteboard: NSPasteboard) -> Bool {
        let types = Set(pasteboard.types ?? [])
        return concealedTypes.contains(where: types.contains)
    }

    /// Screenshots copied to the clipboard arrive as bare PNG; images copied from apps carry other formats too.
    static func isLikelyScreenshot(_ pasteboard: NSPasteboard) -> Bool {
        guard let items = pasteboard.pasteboardItems, items.count == 1 else { return false }
        return items[0].types == [.png]
    }

    func entries(from pasteboard: NSPasteboard, prefer preference: Preference) -> [ShelfEntry] {
        let files = fileEntries(from: pasteboard)
        if !files.isEmpty { return files }

        switch preference {
        case .images:
            return firstNonEmpty(pasteboard, [imageEntries, linkEntries, textEntries])
        case .text:
            return firstNonEmpty(pasteboard, [linkEntries, textEntries, imageEntries])
        }
    }

    private func firstNonEmpty(_ pasteboard: NSPasteboard,
                               _ readers: [(NSPasteboard) -> [ShelfEntry]]) -> [ShelfEntry] {
        for read in readers {
            let entries = read(pasteboard)
            if !entries.isEmpty { return entries }
        }
        return []
    }

    // MARK: - Representations

    private func fileEntries(from pasteboard: NSPasteboard) -> [ShelfEntry] {
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
        return (urls ?? []).map(storage.fileEntry)
    }

    private func linkEntries(_ pasteboard: NSPasteboard) -> [ShelfEntry] {
        var entries: [ShelfEntry] = []
        for item in pasteboard.pasteboardItems ?? [] {
            let title = item.string(forType: .init("public.url-name"))
            if let string = item.string(forType: .URL), let url = Self.webURL(string) {
                entries.compactAppend(storage.linkEntry(url, title: title))
            } else if let string = item.string(forType: .string), let url = Self.webURL(string) {
                entries.compactAppend(storage.linkEntry(url, title: title))
            } else {
                // Mixed content (a link and a paragraph) reads as text instead.
                return []
            }
        }
        return entries
    }

    private func textEntries(_ pasteboard: NSPasteboard) -> [ShelfEntry] {
        var entries: [ShelfEntry] = []
        for item in pasteboard.pasteboardItems ?? [] {
            guard let text = item.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { continue }
            entries.compactAppend(storage.textEntry(text, rtf: item.data(forType: .rtf)))
        }
        return entries
    }

    private func imageEntries(_ pasteboard: NSPasteboard) -> [ShelfEntry] {
        var entries: [ShelfEntry] = []
        for item in pasteboard.pasteboardItems ?? [] {
            guard let type = Self.imageTypes.first(where: { item.types.contains($0) }),
                  let data = item.data(forType: type),
                  let uti = UTType(type.rawValue) else { continue }
            entries.compactAppend(storage.imageEntry(data, type: uti))
        }
        return entries
    }

    /// A single http(s) address, nothing around it.
    static func webURL(_ string: String) -> URL? {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme),
              url.host() != nil else { return nil }
        return url
    }
}

private extension Array {
    mutating func compactAppend(_ element: Element?) {
        if let element { append(element) }
    }
}
